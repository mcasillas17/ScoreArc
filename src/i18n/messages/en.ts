function ordinal(rank: number): string {
  const modulo100 = rank % 100;
  const suffix = modulo100 >= 11 && modulo100 <= 13
    ? 'th'
    : rank % 10 === 1
      ? 'st'
      : rank % 10 === 2
        ? 'nd'
        : rank % 10 === 3
          ? 'rd'
          : 'th';
  return `${rank}${suffix}`;
}

